#!/usr/bin/env node
// Make a private, per-agent copy of the Guildworks plugin whose connector is pinned to one agent's
// address. Claude shares one connector list across chat, Projects, Cowork and Code, so when one account
// hosts several agents, each agent needs its own address (/mcp/<name>). Install one copy per agent.
//
// The copies name your agents, so they are written OUTSIDE this public repository, into a folder you
// keep (with its own marketplace), never into plugins/ here.
//
//   node scripts/agent-plugin.mjs --out ~/guildworks-agents <AgentName>...
//   /plugin marketplace add ~/guildworks-agents
//   /plugin install guildworks-<agent-name>@guildworks-agents
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const BASE = join(ROOT, 'plugins/guildworks');
const ORIGIN = 'https://app.guildworks.io';
const read = p => JSON.parse(readFileSync(p, 'utf8'));
const write = (p, v) => writeFileSync(p, `${JSON.stringify(v, null, 2)}\n`);

function slugOf(name) {
  const slug = name.trim().toLowerCase().replace(/\s+/g, '-');
  if (!/^[a-z0-9][a-z0-9-]{0,39}$/.test(slug)) throw new Error(`Agent name "${name}" must be letters, digits and spaces`);
  return slug;
}

function build(name, dir) {
  const slug = slugOf(name), id = `guildworks-${slug}`, url = `${ORIGIN}/mcp/${slug}`;
  const label = `Guildworks ${name}`, about = `Guildworks for your agent ${name}: this plugin's connector only ever signs in as ${name}.`;
  rmSync(dir, { recursive: true, force: true });
  cpSync(BASE, dir, { recursive: true });
  write(join(dir, '.mcp.json'), { mcpServers: { [id]: { type: 'http', url } } });
  const mcp = read(join(dir, 'mcp.json'));
  mcp.mcpServers = { [id]: { ...mcp.mcpServers.guildworks, url } };
  write(join(dir, 'mcp.json'), mcp);
  const claude = read(join(dir, '.claude-plugin/plugin.json'));
  Object.assign(claude, { name: id, displayName: label, description: about });
  write(join(dir, '.claude-plugin/plugin.json'), claude);
  const codex = read(join(dir, '.codex-plugin/plugin.json'));
  Object.assign(codex, { name: id, description: about });
  Object.assign(codex.interface, { displayName: label });
  write(join(dir, '.codex-plugin/plugin.json'), codex);
  const open = read(join(dir, 'plugin.json'));
  Object.assign(open, { name: id, description: about });
  Object.assign(open.extensions['com.openai'].interface, { displayName: label });
  write(join(dir, 'plugin.json'), open);
  const connect = join(dir, 'skills/connect/SKILL.md');
  writeFileSync(connect, readFileSync(connect, 'utf8').replace('Call `gw_access_extension_status`. Read `you.name`.',
    `This plugin is for **${name}**. Its connector is \`${url}\` and only ever signs in as ${name}.\nUse it only if you are ${name}; otherwise use your own agent's plugin.\n\nCall \`gw_access_extension_status\`. Read \`you.name\`.`));
  writeFileSync(join(dir, 'README.md'), `# ${label}

The [Guildworks plugin](../guildworks/README.md) pinned to one agent, **${name}**. Its connector is
\`${url}\`, so it can only ever sign in as ${name}, even when the same Claude account also hosts other
agents. Use it when one Claude account runs several Guildworks agents: install one per-agent plugin for
each, and leave out the shared \`guildworks\` plugin, which signs in as whichever agent you approved last.

Install it, connect, and approve ${name} on the Guildworks page that opens. If ${name} already exists in
your workspace, Guildworks offers only that agent ("Also use it from this app"); if not, it creates
${name}. The skills, tools and policies are the same as the main plugin's.

Generated by \`scripts/agent-plugin.mjs\` from the public Guildworks plugin. Keep this folder private,
and run the script again after updating the main plugin rather than editing it here.
`);
  return { id, name, slug };
}

const args = process.argv.slice(2), at = args.indexOf('--out');
if (at < 0 || !args[at + 1] || args.length < 3) {
  console.error('Usage: node scripts/agent-plugin.mjs --out <private folder outside this repo> <AgentName>...');
  process.exit(2);
}
const out = resolve(args[at + 1].replace(/^~(?=\/|$)/, process.env.HOME ?? '~'));
if (out === resolve(ROOT) || out.startsWith(`${resolve(ROOT)}/`)) {
  console.error('Write agent plugins outside this public repository: they name your agents.');
  process.exit(2);
}
const names = args.filter((_, i) => i !== at && i !== at + 1);
mkdirSync(join(out, 'plugins'), { recursive: true });
mkdirSync(join(out, '.claude-plugin'), { recursive: true });
const plugins = names.map(name => {
  const { id, slug } = build(name, join(out, 'plugins', `guildworks-${slugOf(name)}`));
  console.log(join(out, 'plugins', id));
  return { name: id, source: `./plugins/${id}`, description: `Guildworks pinned to the agent ${name} (/mcp/${slug}).`, category: 'productivity' };
});
write(join(out, '.claude-plugin/marketplace.json'), { name: 'guildworks-agents', owner: { name: 'Private' }, metadata: { description: 'Private per-agent Guildworks plugins.' }, plugins });
